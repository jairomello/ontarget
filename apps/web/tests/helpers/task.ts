import type { Task } from "../../src/store/types";

/** Cria uma tarefa de teste com todos os campos do contrato da API. */
export function makeTask(
  id: string,
  name: string,
  options: Partial<Task> = {},
): Task {
  const now = Date.now();
  return {
    id,
    projectId: "p1",
    parentId: null,
    outlineLevel: 0,
    outlineNumber: "1",
    sortOrder: 0,
    name,
    notes: null,
    isSummary: false,
    isMilestone: false,
    isInactive: false,
    schedulingMode: "auto",
    isPlaceholder: false,
    taskType: "fixed_duration",
    effortDriven: true,
    constraintType: null,
    constraintDate: null,
    deadline: null,
    manualStart: null,
    manualFinish: null,
    manualDuration: null,
    start: now,
    finish: now + 86_400_000,
    duration: 86_400_000,
    durationUnit: "day",
    work: null,
    cost: null,
    fixedCost: null,
    actualStart: null,
    actualFinish: null,
    actualDuration: null,
    actualWork: null,
    actualCost: null,
    percentComplete: 0,
    physicalPercent: null,
    durationEstimated: true,
    priority: 500,
    calendarId: null,
    wbsCode: null,
    recurrence: null,
    segments: null,
    createdAt: now,
    updatedAt: now,
    ...options,
  };
}
